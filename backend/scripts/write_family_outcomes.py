def main() -> int:
    parser = argparse.ArgumentParser(description="补写家族与子嗣栏目中家族成员的结局")
    parser.add_argument("--dry-run", action="store_true", help="只打印将写入的人物与行数，不写库")
    args = parser.parse_args()

    if args.dry_run:
        for person_id, content in sorted(FAMILY_OUTCOMES.items()):
            print(f"{person_id}\t{len(content.splitlines())} 行")
        return 0

    database_path = BACKEND_DIRECTORY / "data" / "ming_history.sqlite3"
    with sqlite3.connect(database_path) as db:
        missing = []
        for person_id, content in sorted(FAMILY_OUTCOMES.items()):
            row = db.execute(
                "SELECT 1 FROM person_section WHERE person_id = ? AND section_key = 'family'",
                (person_id,),
            ).fetchone()
            if row:
                db.execute(
                    "UPDATE person_section SET content = ? WHERE person_id = ? AND section_key = 'family'",
                    (content, person_id),
                )
            else:
                db.execute(
                    "INSERT INTO person_section(person_id, section_key, title, position, content) VALUES (?, 'family', '家族', 1, ?)",
                    (person_id, content),
                )
            db.execute("UPDATE person SET family_summary = ? WHERE id = ?", (content, person_id))
            if not db.execute("SELECT 1 FROM person WHERE id = ?", (person_id,)).fetchone():
                missing.append(person_id)
        if missing:
            raise SystemExit(f"以下人物不存在：{', '.join(missing)}")
    print(f"已写入 {len(FAMILY_OUTCOMES)} 位人物的家族结局。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
