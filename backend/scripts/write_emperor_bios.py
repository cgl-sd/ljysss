def main() -> int:
    initialize_database()
    written = 0
    with connect() as db:
        for person_id, bio in EMPEROR_BIOS.items():
            row = db.execute("SELECT 1 FROM person WHERE id = ?", (person_id,)).fetchone()
            if not row:
                print(f"跳过不存在的 {person_id}", flush=True)
                continue
            current = db.execute(
                "SELECT content FROM person_section WHERE person_id = ? AND section_key = 'life'",
                (person_id,),
            ).fetchone()
            shi_block = ""
            if current and "〔《明史》原文" in current["content"]:
                shi_block = current["content"][current["content"].index("〔《明史》原文"):].strip()
            content = bio + ("\n\n" + shi_block if shi_block else "")
            db.execute(
                """
                INSERT INTO person_section(person_id, section_key, title, position, content)
                VALUES (?, 'life', '生平', 0, ?)
                ON CONFLICT(person_id, section_key) DO UPDATE SET content = excluded.content
                """,
                (person_id, content),
            )
            db.execute(
                "UPDATE person SET biography = ? WHERE id = ?",
                (bio, person_id),
            )
            written += 1
    print(f"帝王详细传记写库 {written} 位。", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
